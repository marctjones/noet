/// Push the current find state into the editor (highlights + caret to the active
/// match) and re-render; update the bar's count/position.
fn find_apply(ui: &AppWindow) {
    let hits = FIND_HITS.with(|h| h.borrow().clone());
    let cur = FIND_CUR.with(|c| c.get());
    RICH.with(|r| {
        let mut e = r.borrow_mut();
        e.set_search_highlights(&hits, if hits.is_empty() { None } else { Some(cur) });
        if let Some(m) = hits.get(cur) {
            e.core_mut().set_cursor(m.0);
        }
    });
    rich_render(ui, true);
    ui.set_find_count(hits.len() as i32);
    ui.set_find_current(if hits.is_empty() { 0 } else { (cur + 1) as i32 });
}

// ---- WYSIWYG (sred) editor bridge ---------------------------------------------
// The raw TextEdit binds `text <=> current-body`; sred instead owns the buffer in
// RICH and we mirror `current-body` from `ed.text()` after each edit, so the
// existing autosave / preview / chip pipeline (driven by `note-edited`) is reused
// unchanged. sred renders the whole document to an RGBA image; the Slint surface
// shows it in a Flickable and forwards key/pointer events back here.

/// Build a sred [`SredTheme`] from Noet's live palette (dark flag) + font zoom.
fn sred_theme(ui: &AppWindow) -> SredTheme {
    let dark = ui.global::<Theme>().get_dark();
    let z = ui.global::<Z>().get_f().max(0.5);
    let mut t = SredTheme::default();
    t.font_size *= z;
    t.line_height *= z;
    t.margin_x *= z;
    t.margin_y *= z;
    if dark {
        t.fg = [231, 234, 239, 255];
        t.bg = [30, 33, 39, 255];
        t.link = [110, 165, 255, 255];
        t.code = [210, 150, 230, 255];
        t.selection = [60, 110, 170, 110];
    }
    t
}

fn rgba_to_image(rgba: &[u8], width: u32, height: u32) -> slint::Image {
    let mut buf = slint::SharedPixelBuffer::<slint::Rgba8Pixel>::new(width, height);
    buf.make_mut_bytes().copy_from_slice(rgba);
    slint::Image::from_rgba8(buf)
}

/// Re-rasterize the sred document and push frame + caret + scroll to the UI.
/// Honors any wheel/scrollbar offset the Slint side set since the last render.
/// Render the visible slice via sred's viewport-bounded path (flat per-keystroke
/// cost regardless of note length). `follow` keeps the caret on screen after
/// edits/clicks; pass `false` for plain scrolling so the view doesn't snap back.
fn rich_render(ui: &AppWindow, follow: bool) {
    let (w, h) = RICH_VP.with(|v| v.get());
    let theme = sred_theme(ui);
    let ui_scroll = ui.get_rich_scroll_y();
    RICH.with(|r| {
        let mut e = r.borrow_mut();
        e.set_theme(theme);
        e.set_viewport(w, h);
        e.scroll_to(ui_scroll);
        // Viewport-sized frame + viewport-relative caret + resolved scroll. With the
        // `typst-math` feature, sred composites rendered math/figure fragments into
        // this frame itself (set_fragment_overlay, sred #24).
        let out = e.render_view(follow);
        ui.set_rich_frame(rgba_to_image(&out.frame.rgba, out.frame.width, out.frame.height));
        ui.set_rich_doc_height(out.doc_height as f32);
        ui.set_rich_caret_x(out.caret.x);
        ui.set_rich_caret_y(out.caret.y);
        ui.set_rich_caret_h(out.caret.h);
        ui.set_rich_scroll_y(out.scroll_y);
        // Accessibility: expose the document text to the a11y tree (sred renders a
        // bitmap that screen readers can't see).
        ui.set_rich_a11y(e.a11y().value.into());
    });
}

/// After a content-changing edit: mirror the buffer into `current-body`, re-render
/// the frame, then run the shared live-update + debounced-autosave pipeline.
fn rich_after_edit(ui: &AppWindow) {
    let body = RICH.with(|r| r.borrow().text());
    ui.set_current_body(body.into());
    rich_render(ui, true);
    ui.invoke_note_edited();
}

/// Load a note body into the sred editor and show it from the top.
fn rich_load(ui: &AppWindow, body: &str) {
    RICH.with(|r| r.borrow_mut().set_text(body));
    ui.set_rich_scroll_y(0.0);
    // Start each note with the autocomplete popup closed.
    ui.set_rich_ac_open(false);
    AC.with(|a| *a.borrow_mut() = None);
    rich_render(ui, true);
}

/// Re-evaluate inline autocomplete after a typing/caret change: detect a trigger
/// in the text before the caret, fetch matching workstream/person/tag names from
/// the index, and open or close the popup accordingly. Cheap (only on a single
/// caret); skips the query entirely when no trigger is active.
fn rich_autocomplete_update(ui: &AppWindow, state: &Rc<RefCell<State>>) {
    let (text, caret, ncarets) = RICH.with(|r| {
        let e = r.borrow();
        let c = e.carets();
        (e.text(), c.first().copied().unwrap_or(0), c.len())
    });
    let prefix: String = text.chars().take(caret).collect();
    let trig = if ncarets == 1 { ac_detect(&prefix) } else { None };
    let Some((kind, typed)) = trig else {
        ui.set_rich_ac_open(false);
        AC.with(|a| *a.borrow_mut() = None);
        return;
    };
    let lower = typed.to_lowercase();
    let names: Vec<String> = {
        let st = state.borrow();
        let b = &st.backend;
        let raw = match kind {
            "project" => b.list_projects(),
            "person" => b.list_people(),
            _ => b.list_tags(),
        };
        raw.map(|v| v.into_iter().map(|p| p.name).collect()).unwrap_or_default()
    };
    let mut items: Vec<String> =
        names.into_iter().filter(|n| n.to_lowercase().starts_with(&lower)).collect();
    items.sort();
    items.dedup();
    items.truncate(8);
    if items.is_empty() {
        ui.set_rich_ac_open(false);
        AC.with(|a| *a.borrow_mut() = None);
        return;
    }
    let model: Vec<slint::SharedString> = items.iter().map(|s| s.as_str().into()).collect();
    ui.set_rich_ac_items(slint::ModelRc::new(slint::VecModel::from(model)));
    ui.set_rich_ac_index(0);
    ui.set_rich_ac_open(true);
    AC.with(|a| *a.borrow_mut() = Some((kind, typed)));
}

/// Accept the currently-highlighted autocomplete candidate: replace the partial
/// text after the trigger with the full name (canonical casing), closing `]]` for
/// wiki-links, and move the caret past the token. No-op if the popup is closed.
fn rich_autocomplete_accept(ui: &AppWindow) {
    let Some((kind, typed)) = AC.with(|a| a.borrow().clone()) else { return };
    let idx = ui.get_rich_ac_index().max(0) as usize;
    let items = ui.get_rich_ac_items();
    let Some(name) = items.row_data(idx) else { return };
    let name = name.to_string();
    RICH.with(|r| {
        let mut e = r.borrow_mut();
        // Delete what the user already typed after the trigger (so casing is canonical).
        for _ in 0..typed.chars().count() {
            e.apply(SredCmd::DeleteBackward);
        }
        if kind == "tag" {
            e.apply(SredCmd::Insert(name));
        } else {
            // Wiki-link: don't double the closing `]]` if it's already there
            // (auto-pairs may have inserted it); otherwise add it. End past the `]]`.
            let after_close = {
                let t = e.text();
                let c = e.carets().first().copied().unwrap_or(0);
                t.chars().skip(c).take(2).collect::<String>() == "]]"
            };
            e.apply(SredCmd::Insert(name));
            if after_close {
                e.apply(SredCmd::Move(SredMotion::Right));
                e.apply(SredCmd::Move(SredMotion::Right));
            } else {
                e.apply(SredCmd::Insert("]]".to_string()));
            }
        }
    });
    ui.set_rich_ac_open(false);
    AC.with(|a| *a.borrow_mut() = None);
    rich_after_edit(ui);
}

// ---- sred domain tokens: color `[[wikilink]]` / `@mention` / `#tag` / url in
// the editor and make them clickable (route to the existing facet filters). ----

/// Find `[[Name]]` runs in a line; value = the inner name.
fn find_wikilinks(line: &str) -> Vec<SredMatch> {
    let c: Vec<char> = line.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i + 1 < c.len() {
        if c[i] == '[' && c[i + 1] == '[' {
            if let Some(close) = (i + 2..c.len().saturating_sub(1)).find(|&k| c[k] == ']' && c[k + 1] == ']') {
                out.push(SredMatch { start: i, end: close + 2, value: c[i + 2..close].iter().collect() });
                i = close + 2;
                continue;
            }
        }
        i += 1;
    }
    out
}

/// Find `@[[Name]]` or bare `@name` mentions.
fn find_mentions(line: &str) -> Vec<SredMatch> {
    let c: Vec<char> = line.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < c.len() {
        let boundary = i == 0 || c[i - 1].is_whitespace();
        if boundary && c[i] == '@' {
            if i + 2 < c.len() && c[i + 1] == '[' && c[i + 2] == '[' {
                if let Some(close) = (i + 3..c.len().saturating_sub(1)).find(|&k| c[k] == ']' && c[k + 1] == ']') {
                    out.push(SredMatch { start: i, end: close + 2, value: c[i + 3..close].iter().collect() });
                    i = close + 2;
                    continue;
                }
            }
            let mut j = i + 1;
            while j < c.len() && (c[j].is_alphanumeric() || matches!(c[j], '.' | '-' | '_')) {
                j += 1;
            }
            if j > i + 1 {
                out.push(SredMatch { start: i, end: j, value: c[i + 1..j].iter().collect() });
                i = j;
                continue;
            }
        }
        i += 1;
    }
    out
}

/// Find `#tag` labels (word-boundary).
fn find_tags(line: &str) -> Vec<SredMatch> {
    let c: Vec<char> = line.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < c.len() {
        let boundary = i == 0 || c[i - 1].is_whitespace();
        if boundary && c[i] == '#' && i + 1 < c.len() && c[i + 1].is_alphabetic() {
            let mut j = i + 1;
            while j < c.len() && (c[j].is_alphanumeric() || matches!(c[j], '_' | '-')) {
                j += 1;
            }
            out.push(SredMatch { start: i, end: j, value: c[i + 1..j].iter().collect() });
            i = j;
            continue;
        }
        i += 1;
    }
    out
}

/// Find `http(s)://…` URLs.
fn find_urls(line: &str) -> Vec<SredMatch> {
    let c: Vec<char> = line.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < c.len() {
        let rest: String = c[i..].iter().collect();
        if rest.starts_with("http://") || rest.starts_with("https://") {
            let mut j = i;
            while j < c.len() && !c[j].is_whitespace() {
                j += 1;
            }
            out.push(SredMatch { start: i, end: j, value: c[i..j].iter().collect() });
            i = j;
            continue;
        }
        i += 1;
    }
    out
}

