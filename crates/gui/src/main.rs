fn resolve_external_url(external: &str) -> Option<String> {
    let ext = external.trim();
    if ext.starts_with("http://") || ext.starts_with("https://") {
        return Some(ext.to_string());
    }
    if let Some(rest) = ext.strip_prefix("ref:") {
        let r = rest.trim();
        if r.starts_with("http://") || r.starts_with("https://") {
            return Some(r.to_string());
        }
    }
    if let Some(rest) = ext.strip_prefix("gh:") {
        let (repo, num) = match rest.split_once('#') {
            Some((r, n)) => (r, Some(n)),
            None => (rest, None),
        };
        let base = format!("https://github.com/{}", repo.trim_end_matches('/'));
        return Some(match num {
            Some(n) if !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()) => {
                format!("{base}/issues/{n}")
            }
            _ => base,
        });
    }
    None
}

/// Rebuild every model from the index + current filter.
pub(crate) fn refresh(ui: &AppWindow, state: &State) {
    let b = &state.backend;
    let f = &state.filter;
    workspace_adapter::sync(ui, &state.app);
    sync_ai_settings_status(ui, &state.app.ai.settings);
    let ai = ai_surface(&state.app.ai);
    ui.set_ai_status(ai.status.into());
    ui.set_ai_progress_active(ai.progress_active);
    ui.set_ai_progress_label(ai.progress_label.into());
    ui.set_ai_progress_detail(ai.progress_detail.into());
    ui.set_ai_progress_elapsed(ai.progress_elapsed.into());
    ui.set_ai_progress_cancellable(ai.progress_cancellable);
    ui.set_ai_pending_count(ai.pending_proposals as i32);
    ui.set_ai_proposals(ModelRc::new(VecModel::from(
        ai.proposals
            .into_iter()
            .map(ai_proposal_ui)
            .collect::<Vec<_>>(),
    )));
    ui.set_ai_jobs(ModelRc::new(VecModel::from(
        ai.jobs.into_iter().map(ai_job_ui).collect::<Vec<_>>(),
    )));
    // Only recompute what the visible view needs. The left-rail facets + filter
    // chrome below always run (they're cheap and shown on every view); the heavy
    // per-view queries (board / agenda / gantt / tasks / person) are gated so a
    // keystroke or filter change doesn't recompute all ten views at once.
    let view = ui.get_view().to_string();
    let workspace_primary = ui.get_workspace_primary().to_string();
    let surface_visible =
        |surface: &str| view == surface || (view == "workspace" && workspace_primary == surface);

    if view == "notes" || view == "workspace" {
        if let Ok(notes) = b.query_notes(f) {
            ui.set_notes(ModelRc::new(VecModel::from(surface_adapters::note_items(
                &notes,
            ))));
        }
    }
    if let Ok(p) = b.list_projects() {
        ui.set_projects(ModelRc::new(VecModel::from(
            surface_adapters::facet_tree_items(&p, &f.project),
        )));
    }
    if let Ok(review) = b.label_review() {
        let maxc = review
            .labels
            .iter()
            .map(|label| label.note_count)
            .max()
            .unwrap_or(1)
            .max(1) as i32;
        ui.set_max_tag_count(maxc);
        ui.set_tags(ModelRc::new(VecModel::from(
            surface_adapters::label_review_items(&review, &f.tag),
        )));
    }
    if f.tag.trim().is_empty() {
        ui.set_label_context_label("".into());
        ui.set_label_context_open_tasks(ModelRc::new(VecModel::from(Vec::<TodoItem>::new())));
        ui.set_label_context_notes(ModelRc::new(VecModel::from(Vec::<NoteRef>::new())));
    } else if let Ok(context) = b.label_context(&f.tag) {
        let surface = surface_adapters::label_context_surface(&context);
        ui.set_label_context_label(surface.label.into());
        ui.set_label_context_open_tasks(ModelRc::new(VecModel::from(surface.open_tasks)));
        ui.set_label_context_notes(ModelRc::new(VecModel::from(surface.notes)));
    } else {
        ui.set_label_context_label("".into());
        ui.set_label_context_open_tasks(ModelRc::new(VecModel::from(Vec::<TodoItem>::new())));
        ui.set_label_context_notes(ModelRc::new(VecModel::from(Vec::<NoteRef>::new())));
    }
    if let Ok(p) = b.list_people() {
        ui.set_people(ModelRc::new(VecModel::from(surface_adapters::facet_items(
            &p, &f.person,
        ))));
    }

    // flat task list (same filtered todos as the board, ungrouped)
    if surface_visible("tasks") {
        if let Ok(tasks) = b.task_list(f) {
            ui.set_tasks(ModelRc::new(VecModel::from(surface_adapters::task_items(
                &tasks,
            ))));
        }
    }

    // "Waiting on": open delegated items, clustered by person, oldest first.
    if view == "waiting" {
        if let Ok(todos) = b.waiting_on() {
            ui.set_waiting_todos(ModelRc::new(VecModel::from(surface_adapters::todo_items(
                &todos,
            ))));
        }
    }

    // Workstream context: one workstream's open todos + filed notes. The old
    // standalone workstream route still works, but workspace label navigation is
    // now the primary path.
    let active_hub = if !f.project.trim().is_empty() {
        f.project.clone()
    } else if view == "workstream" {
        ui.get_hub_name().to_string()
    } else {
        String::new()
    };
    if active_hub.trim().is_empty() {
        ui.set_hub_name("".into());
        ui.set_hub_todos(ModelRc::new(VecModel::from(Vec::<TodoItem>::new())));
        ui.set_hub_notes(ModelRc::new(VecModel::from(Vec::<NoteRef>::new())));
    } else {
        let task_filter = backend::Filter {
            project: active_hub.clone(),
            status: "open".into(),
            ..Default::default()
        };
        let todos = b.query_todos(&task_filter).unwrap_or_default();
        let notes = b
            .query_notes(&backend::Filter {
                project: active_hub.clone(),
                ..Default::default()
            })
            .unwrap_or_default();
        let hub_surface = surface_adapters::workstream_surface(&todos, &notes);
        ui.set_hub_name(active_hub.into());
        ui.set_hub_todos(ModelRc::new(VecModel::from(hub_surface.todos)));
        ui.set_hub_notes(ModelRc::new(VecModel::from(hub_surface.notes)));
    }

    // agenda buckets by due date relative to today
    if view == "agenda" {
        if let Ok(items) = b.agenda(f) {
            let agenda =
                surface_adapters::agenda_surface(&items, chrono::Local::now().date_naive());
            ui.set_agenda_overdue(ModelRc::new(VecModel::from(agenda.overdue)));
            ui.set_agenda_today(ModelRc::new(VecModel::from(agenda.today)));
            ui.set_agenda_week(ModelRc::new(VecModel::from(agenda.week)));
            ui.set_agenda_later(ModelRc::new(VecModel::from(agenda.later)));
        }
    }

    // inbox: unfiled notes
    if view == "inbox" {
        if let Ok(notes) = b.inbox() {
            ui.set_inbox_notes(ModelRc::new(VecModel::from(surface_adapters::note_items(
                &notes,
            ))));
        }
    }

    // today dashboard extras
    if view == "today" {
        if let Ok(stale) = b.stale_todos() {
            ui.set_today_stale(ModelRc::new(VecModel::from(surface_adapters::todo_items(
                &stale,
            ))));
        }
        if let Ok(recent) = b.query_notes(&Filter::default()) {
            ui.set_today_recent(ModelRc::new(VecModel::from(
                surface_adapters::recent_note_items(&recent, 8),
            )));
        }
    }
    if view == "trash" {
        if let Ok(tr) = b.list_trash() {
            ui.set_trash_notes(ModelRc::new(VecModel::from(
                surface_adapters::trash_note_refs(&tr),
            )));
        }
    }
    ui.set_smart_lists(str_model(&b.list_smart_lists()));
    if view == "calendar" {
        let todos = b.query_todos(f).unwrap_or_default();
        let calendar = surface_adapters::calendar_surface(
            &todos,
            state.cal_year,
            state.cal_month,
            chrono::Local::now().date_naive(),
        );
        ui.set_cal_label(calendar.label.into());
        ui.set_cal_cells(ModelRc::new(VecModel::from(calendar.cells)));
    }

    // Standalone 1:1 workspace, keyed by the selected person.
    if view == "oneonone" || (view == "workspace" && workspace_primary == "oneonone") {
        let selected_person = ui.get_selected_person().to_string();
        let workspace_person = if selected_person.trim().is_empty() {
            f.person.clone()
        } else {
            selected_person.trim().to_string()
        };
        if ui.get_selected_person().is_empty() && !workspace_person.is_empty() {
            ui.set_selected_person(workspace_person.clone().into());
        }
        let oneonone_context = if workspace_person.is_empty() {
            None
        } else {
            b.one_on_one_context(&workspace_person).ok()
        };
        let current_id = ui.get_current_id().to_string();
        let oneonone_surface =
            surface_adapters::one_on_one_surface(oneonone_context.as_ref(), &current_id);
        ui.set_person_discuss(ModelRc::new(VecModel::from(oneonone_surface.discuss)));
        ui.set_person_delegated(ModelRc::new(VecModel::from(oneonone_surface.delegated)));
        ui.set_person_delegated_history(ModelRc::new(VecModel::from(
            oneonone_surface.delegated_history,
        )));
        ui.set_person_waiting_delegated(ModelRc::new(VecModel::from(
            oneonone_surface.waiting_delegated,
        )));
        ui.set_person_related_open_loops(ModelRc::new(VecModel::from(
            oneonone_surface.related_open_loops,
        )));
        ui.set_person_other(ModelRc::new(VecModel::from(oneonone_surface.other)));
        ui.set_person_current_oneonone_id(oneonone_surface.current_id.clone().into());
        ui.set_person_current_oneonone_title(oneonone_surface.current_title.clone().into());
        ui.set_person_last_oneonone_title(oneonone_surface.last_title.clone().into());
        ui.set_person_prev_oneonone_id(oneonone_surface.prev_id.clone().into());
        ui.set_person_next_oneonone_id(oneonone_surface.next_id.clone().into());
        ui.set_person_oneonone_index(oneonone_surface.index);
        ui.set_person_oneonone_count(oneonone_surface.count);
        ui.set_person_last_followups(ModelRc::new(VecModel::from(
            oneonone_surface.last_followups,
        )));
        ui.set_person_oneonone_notes(ModelRc::new(VecModel::from(oneonone_surface.history_notes)));
        if !oneonone_surface.current_id.is_empty() && current_id != oneonone_surface.current_id {
            open_in_editor(ui, b, &oneonone_surface.current_id);
            if view == "oneonone" {
                ui.set_view("oneonone".into());
            }
        }
        if oneonone_context.is_some() {
            let pnotes = b
                .query_notes(&Filter {
                    person: workspace_person.clone(),
                    ..Default::default()
                })
                .unwrap_or_default();
            ui.set_person_notes(ModelRc::new(VecModel::from(surface_adapters::note_items(
                &pnotes,
            ))));
        } else {
            ui.set_person_notes(ModelRc::new(VecModel::from(Vec::<NoteItem>::new())));
        }
    }

    if surface_visible("board") {
        let group_by = ui.get_group_by().to_string();
        if let Ok(board) = b.board_model(surface_adapters::board_group_key(&group_by), f) {
            ui.set_board_columns(ModelRc::new(VecModel::from(
                surface_adapters::board_columns(&board),
            )));
        }
    }

    if surface_visible("review") {
        if let Ok(review) = b.task_review() {
            let review_surface = surface_adapters::task_review_surface(&review);
            ui.set_review_overdue(ModelRc::new(VecModel::from(review_surface.overdue)));
            ui.set_review_due(ModelRc::new(VecModel::from(review_surface.due)));
            ui.set_review_stale(ModelRc::new(VecModel::from(review_surface.stale)));
            ui.set_review_followups(ModelRc::new(VecModel::from(review_surface.followups)));
            ui.set_review_someday(ModelRc::new(VecModel::from(review_surface.someday)));
        }
        if let Ok(waiting) = b.waiting_review() {
            let tasks = surface_adapters::waiting_review_items(&waiting);
            ui.set_review_waiting(ModelRc::new(VecModel::from(tasks.clone())));
            ui.set_waiting_todos(ModelRc::new(VecModel::from(tasks)));
        }
        if let Ok(notes) = b.inbox() {
            ui.set_review_inbox_notes(ModelRc::new(VecModel::from(surface_adapters::note_items(
                &notes,
            ))));
        }
    }

    if view == "gantt" {
        if let Ok(g) = b.gantt_items(f) {
            ui.set_gantt_items(ModelRc::new(VecModel::from(surface_adapters::gantt_items(
                &g,
            ))));
        }
    }

    ui.set_active_summary(surface_adapters::active_summary(f).into());

    // removable active-filter chips + dropdown display values
    ui.set_active_filters(ModelRc::new(VecModel::from(
        surface_adapters::active_filter_chips(f),
    )));
    ui.set_filter_kind(surface_adapters::filter_value_or_any(&f.kind).into());
    ui.set_filter_priority(surface_adapters::filter_value_or_any(&f.priority).into());
    ui.set_filter_due(surface_adapters::due_display(&f.due_bucket).into());
    refresh_tabs(ui, state); // keep the open-notes tab strip in sync
    ui_trace::refresh(ui, state);
}

