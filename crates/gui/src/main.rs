fn resolve_external_url(external: &str) -> Option<String> {
    let ext = external.trim();
    if ext.starts_with("http://") || ext.starts_with("https://") {
        return Some(ext.to_string());
    }
    if let Some(rest) = ext.strip_prefix("ref:") {
        let r = rest.trim();
        if r.starts_with("http://") || r.starts_with("https://") {
            return Some(r.to_string());
        }
    }
    if let Some(rest) = ext.strip_prefix("gh:") {
        let (repo, num) = match rest.split_once('#') {
            Some((r, n)) => (r, Some(n)),
            None => (rest, None),
        };
        let base = format!("https://github.com/{}", repo.trim_end_matches('/'));
        return Some(match num {
            Some(n) if !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()) => {
                format!("{base}/issues/{n}")
            }
            _ => base,
        });
    }
    None
}

fn active_summary(f: &Filter) -> String {
    let mut parts = Vec::new();
    if !f.project.is_empty() {
        parts.push(format!("▸{}", f.project));
    }
    if !f.tag.is_empty() {
        parts.push(format!("#{}", f.tag));
    }
    if !f.person.is_empty() {
        parts.push(format!("@{}", f.person));
    }
    if !f.search.is_empty() {
        parts.push(format!("“{}”", f.search));
    }
    if !f.status.is_empty() {
        parts.push(f.status.clone());
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!("Filtered: {}", parts.join("  ·  "))
    }
}

/// Rebuild every model from the index + current filter.
pub(crate) fn refresh(ui: &AppWindow, state: &State) {
    let b = &state.backend;
    let f = &state.filter;
    workspace_adapter::sync(ui, &state.app);
    // Only recompute what the visible view needs. The left-rail facets + filter
    // chrome below always run (they're cheap and shown on every view); the heavy
    // per-view queries (board / agenda / gantt / tasks / person) are gated so a
    // keystroke or filter change doesn't recompute all ten views at once.
    let view = ui.get_view().to_string();
    let workspace_primary = ui.get_workspace_primary().to_string();
    let surface_visible =
        |surface: &str| view == surface || (view == "workspace" && workspace_primary == surface);

    if view == "notes" || view == "workspace" {
        if let Ok(notes) = b.query_notes(f) {
            let items: Vec<NoteItem> = notes.iter().map(to_note_item).collect();
            ui.set_notes(ModelRc::new(VecModel::from(items)));
        }
    }
    if let Ok(p) = b.list_projects() {
        ui.set_projects(facet_tree(&p, &f.project));
    }
    if let Ok(t) = b.list_tags() {
        let maxc = t.iter().map(|x| x.count).max().unwrap_or(1).max(1) as i32;
        ui.set_max_tag_count(maxc);
        ui.set_tags(facet_tree(&t, &f.tag));
    }
    if let Ok(p) = b.list_people() {
        ui.set_people(facet(&p, &f.person));
    }

    // flat task list (same filtered todos as the board, ungrouped)
    if surface_visible("tasks") {
        if let Ok(tasks) = b.task_list(f) {
            let items: Vec<TodoItem> = tasks.iter().map(to_todo_item_from_fact).collect();
            ui.set_tasks(ModelRc::new(VecModel::from(items)));
        }
    }

    // "Waiting on": open delegated items, clustered by person, oldest first.
    if view == "waiting" {
        if let Ok(todos) = b.waiting_on() {
            let items: Vec<TodoItem> = todos.iter().map(to_todo_item).collect();
            ui.set_waiting_todos(ModelRc::new(VecModel::from(items)));
        }
    }

    // Workstream hub: one workstream's open todos + the notes that reference it.
    if view == "workstream" {
        let hub = ui.get_hub_name().to_string();
        let f = backend::Filter {
            project: hub.clone(),
            status: "open".into(),
            ..Default::default()
        };
        if let Ok(todos) = b.query_todos(&f) {
            let items: Vec<TodoItem> = todos.iter().map(to_todo_item).collect();
            ui.set_hub_todos(ModelRc::new(VecModel::from(items)));
        }
        let notes: Vec<NoteRef> = b
            .backlinks(&hub)
            .unwrap_or_default()
            .into_iter()
            .map(|n| NoteRef {
                id: n.id.into(),
                title: n.title.into(),
            })
            .collect();
        ui.set_hub_notes(ModelRc::new(VecModel::from(notes)));
    }

    // agenda buckets by due date relative to today
    if view == "agenda" {
        if let Ok(items) = b.agenda(f) {
            let today = chrono::Local::now().format("%Y-%m-%d").to_string();
            let week = (chrono::Local::now() + chrono::Duration::days(7))
                .format("%Y-%m-%d")
                .to_string();
            let (mut overdue, mut td, mut wk, mut later) = (vec![], vec![], vec![], vec![]);
            for t in &items {
                let it = to_todo_item(t);
                if t.due < today {
                    overdue.push(it);
                } else if t.due == today {
                    td.push(it);
                } else if t.due <= week {
                    wk.push(it);
                } else {
                    later.push(it);
                }
            }
            ui.set_agenda_overdue(ModelRc::new(VecModel::from(overdue)));
            ui.set_agenda_today(ModelRc::new(VecModel::from(td)));
            ui.set_agenda_week(ModelRc::new(VecModel::from(wk)));
            ui.set_agenda_later(ModelRc::new(VecModel::from(later)));
        }
    }

    // inbox: unfiled notes
    if view == "inbox" {
        if let Ok(notes) = b.inbox() {
            let items: Vec<NoteItem> = notes.iter().map(to_note_item).collect();
            ui.set_inbox_notes(ModelRc::new(VecModel::from(items)));
        }
    }

    // today dashboard extras
    if view == "today" {
        if let Ok(stale) = b.stale_todos() {
            ui.set_today_stale(ModelRc::new(VecModel::from(
                stale.iter().map(to_todo_item).collect::<Vec<_>>(),
            )));
        }
        if let Ok(recent) = b.query_notes(&Filter::default()) {
            let items: Vec<NoteItem> = recent.iter().take(8).map(to_note_item).collect();
            ui.set_today_recent(ModelRc::new(VecModel::from(items)));
        }
    }
    if view == "trash" {
        if let Ok(tr) = b.list_trash() {
            let items: Vec<NoteRef> = tr
                .iter()
                .map(|(f, t)| NoteRef {
                    id: f.clone().into(),
                    title: t.clone().into(),
                })
                .collect();
            ui.set_trash_notes(ModelRc::new(VecModel::from(items)));
        }
    }
    ui.set_smart_lists(str_model(&b.list_smart_lists()));
    if view == "calendar" {
        let (cl, cc) = build_calendar(b, f, state.cal_year, state.cal_month);
        ui.set_cal_label(cl.into());
        ui.set_cal_cells(cc);
    }

    // Standalone 1:1 workspace, keyed by the selected person.
    if view == "oneonone" || (view == "workspace" && workspace_primary == "oneonone") {
        let selected_person = ui.get_selected_person().to_string();
        let workspace_person = if selected_person.trim().is_empty() {
            f.person.clone()
        } else {
            selected_person.trim().to_string()
        };
        if ui.get_selected_person().is_empty() && !workspace_person.is_empty() {
            ui.set_selected_person(workspace_person.clone().into());
        }
        let oneonone_context = if workspace_person.is_empty() {
            None
        } else {
            b.one_on_one_context(&workspace_person).ok()
        };
        let empty_todos = || ModelRc::new(VecModel::from(Vec::<TodoItem>::new()));
        let empty_notes = || ModelRc::new(VecModel::from(Vec::<NoteItem>::new()));
        if let Some(oneonone_context) = oneonone_context {
            let mut discuss = oneonone_context.followups.clone();
            discuss.extend(oneonone_context.waiting.clone());
            ui.set_person_discuss(ModelRc::new(VecModel::from(
                discuss
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            ui.set_person_delegated(ModelRc::new(VecModel::from(
                oneonone_context
                    .delegated
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            ui.set_person_delegated_history(ModelRc::new(VecModel::from(
                oneonone_context
                    .open_items
                    .iter()
                    .filter(|t| {
                        matches!(
                            &t.workflow,
                            backend::TaskWorkflow::Delegated
                                | backend::TaskWorkflow::Followup
                                | backend::TaskWorkflow::Waiting
                        )
                    })
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            ui.set_person_other(ModelRc::new(VecModel::from(
                oneonone_context
                    .open_items
                    .iter()
                    .filter(|t| {
                        !matches!(
                            &t.workflow,
                            backend::TaskWorkflow::Delegated
                                | backend::TaskWorkflow::Followup
                                | backend::TaskWorkflow::Waiting
                        )
                    })
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            let oneonone_notes = oneonone_context.history.clone();
            let current_id = ui.get_current_id().to_string();
            let current_idx = oneonone_notes
                .iter()
                .position(|n| n.id == current_id)
                .unwrap_or(0);
            let current_oneonone = oneonone_notes.get(current_idx);
            let prev_oneonone = if current_idx > 0 {
                oneonone_notes.get(current_idx - 1)
            } else {
                None
            };
            let next_oneonone = oneonone_notes.get(current_idx + 1);
            let last_oneonone = next_oneonone;
            let last_followups = if let Some(prev) = last_oneonone {
                oneonone_context
                    .open_items
                    .iter()
                    .filter(|t| {
                        t.source.note_id == prev.id
                            && matches!(
                                &t.workflow,
                                backend::TaskWorkflow::Followup
                                    | backend::TaskWorkflow::Delegated
                                    | backend::TaskWorkflow::Waiting
                            )
                    })
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>()
            } else {
                Vec::new()
            };
            if let Some(n) = current_oneonone {
                ui.set_person_current_oneonone_id(n.id.clone().into());
                ui.set_person_current_oneonone_title(n.title.clone().into());
                if current_id != n.id {
                    open_in_editor(ui, b, &n.id);
                    if view == "oneonone" {
                        ui.set_view("oneonone".into());
                    }
                }
            } else {
                ui.set_person_current_oneonone_id("".into());
                ui.set_person_current_oneonone_title("".into());
            }
            ui.set_person_last_oneonone_title(
                last_oneonone
                    .map(|n| n.title.clone())
                    .unwrap_or_default()
                    .into(),
            );
            ui.set_person_prev_oneonone_id(
                prev_oneonone
                    .map(|n| n.id.clone())
                    .unwrap_or_default()
                    .into(),
            );
            ui.set_person_next_oneonone_id(
                next_oneonone
                    .map(|n| n.id.clone())
                    .unwrap_or_default()
                    .into(),
            );
            ui.set_person_oneonone_index(current_idx as i32);
            ui.set_person_oneonone_count(oneonone_notes.len() as i32);
            ui.set_person_last_followups(ModelRc::new(VecModel::from(last_followups)));
            ui.set_person_oneonone_notes(ModelRc::new(VecModel::from(
                oneonone_notes
                    .iter()
                    .map(to_note_item_from_summary)
                    .collect::<Vec<_>>(),
            )));
            let pnotes = b
                .query_notes(&Filter {
                    person: workspace_person.clone(),
                    ..Default::default()
                })
                .unwrap_or_default();
            ui.set_person_notes(ModelRc::new(VecModel::from(
                pnotes.iter().map(to_note_item).collect::<Vec<_>>(),
            )));
        } else {
            ui.set_person_discuss(empty_todos());
            ui.set_person_delegated(empty_todos());
            ui.set_person_delegated_history(empty_todos());
            ui.set_person_other(empty_todos());
            ui.set_person_current_oneonone_id("".into());
            ui.set_person_current_oneonone_title("".into());
            ui.set_person_last_oneonone_title("".into());
            ui.set_person_prev_oneonone_id("".into());
            ui.set_person_next_oneonone_id("".into());
            ui.set_person_oneonone_index(0);
            ui.set_person_oneonone_count(0);
            ui.set_person_last_followups(empty_todos());
            ui.set_person_oneonone_notes(empty_notes());
            ui.set_person_notes(empty_notes());
        }
    }

    if surface_visible("board") {
        let group_by = ui.get_group_by().to_string();
        if let Ok(board) = b.board_model(board_group_key(&group_by), f) {
            let items: Vec<BoardColumn> = board
                .columns
                .into_iter()
                .map(|col| {
                    let cards: Vec<TodoItem> =
                        col.tasks.iter().map(to_todo_item_from_fact).collect();
                    BoardColumn {
                        title: col.label.into(),
                        key: col.key.into(),
                        count: cards.len() as i32,
                        cards: ModelRc::new(VecModel::from(cards)),
                    }
                })
                .collect();
            ui.set_board_columns(ModelRc::new(VecModel::from(items)));
        }
    }

    if surface_visible("review") {
        if let Ok(review) = b.task_review() {
            let overdue_ids = review
                .overdue
                .iter()
                .map(|task| task.id.as_str())
                .collect::<std::collections::HashSet<_>>();
            let due = review
                .due
                .iter()
                .filter(|task| !overdue_ids.contains(task.id.as_str()))
                .map(to_todo_item_from_fact)
                .collect::<Vec<_>>();
            ui.set_review_overdue(ModelRc::new(VecModel::from(
                review
                    .overdue
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            ui.set_review_due(ModelRc::new(VecModel::from(due)));
            ui.set_review_stale(ModelRc::new(VecModel::from(
                review
                    .stale
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            ui.set_review_followups(ModelRc::new(VecModel::from(
                review
                    .followups
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
            ui.set_review_someday(ModelRc::new(VecModel::from(
                review
                    .someday
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            )));
        }
        if let Ok(waiting) = b.waiting_review() {
            let mut tasks = waiting
                .groups
                .into_iter()
                .flat_map(|group| group.tasks)
                .map(|task| to_todo_item_from_fact(&task))
                .collect::<Vec<_>>();
            tasks.extend(
                waiting
                    .unassigned
                    .iter()
                    .map(to_todo_item_from_fact)
                    .collect::<Vec<_>>(),
            );
            ui.set_review_waiting(ModelRc::new(VecModel::from(tasks.clone())));
            ui.set_waiting_todos(ModelRc::new(VecModel::from(tasks)));
        }
        if let Ok(notes) = b.inbox() {
            ui.set_review_inbox_notes(ModelRc::new(VecModel::from(
                notes.iter().map(to_note_item).collect::<Vec<_>>(),
            )));
        }
    }

    if view == "gantt" {
        if let Ok(g) = b.gantt_items(f) {
            ui.set_gantt_items(ModelRc::new(VecModel::from(build_gantt(&g))));
        }
    }

    ui.set_active_summary(active_summary(f).into());

    // removable active-filter chips + dropdown display values
    let mut chips: Vec<FilterChip> = Vec::new();
    let mut chip = |label: String, dim: &str| {
        chips.push(FilterChip {
            label: label.into(),
            dim: dim.into(),
        })
    };
    if !f.project.is_empty() {
        chip(format!("▸ {}", f.project), "project");
    }
    if !f.person.is_empty() {
        chip(format!("@ {}", f.person), "person");
    }
    if !f.tag.is_empty() {
        chip(format!("# {}", f.tag), "tag");
    }
    if !f.kind.is_empty() {
        chip(format!("workflow: {}", f.kind), "kind");
    }
    if !f.priority.is_empty() {
        chip(format!("priority {}", f.priority), "priority");
    }
    if !f.due_bucket.is_empty() {
        chip(format!("due: {}", due_display(&f.due_bucket)), "due");
    }
    if !f.status.is_empty() {
        chip(format!("status: {}", f.status), "status");
    }
    if !f.search.is_empty() {
        chip(format!("search: {}", f.search), "search");
    }
    ui.set_active_filters(ModelRc::new(VecModel::from(chips)));
    ui.set_filter_kind(if f.kind.is_empty() {
        "any".into()
    } else {
        f.kind.clone().into()
    });
    ui.set_filter_priority(if f.priority.is_empty() {
        "any".into()
    } else {
        f.priority.clone().into()
    });
    ui.set_filter_due(due_display(&f.due_bucket).into());
    refresh_tabs(ui, state); // keep the open-notes tab strip in sync
}

fn md_blocks_model(
    b: &Backend,
    note_id: &str,
    body: &str,
    render_typst: bool,
    folded: &std::collections::HashSet<usize>,
) -> ModelRc<MdBlock> {
    let todos = backend::parse_todos(note_id, body);
    let mut ti = todos.iter();
    let empty = slint::Image::default();
    let mut out: Vec<MdBlock> = Vec::new();
    let no_segs = || ModelRc::new(VecModel::from(Vec::<Segment>::new()));
    let empty_task_fields = || {
        (
            SharedString::from(""),
            SharedString::from(""),
            SharedString::from(""),
            SharedString::from(""),
            SharedString::from(""),
        )
    };
    let mut hide_level: Option<i32> = None; // hide blocks under a folded heading
    for (idx, x) in backend::markdown_blocks(body).into_iter().enumerate() {
        let level = match x.kind.as_str() {
            "h1" => 1,
            "h2" => 2,
            "h3" => 3,
            _ => 99,
        };
        // keep the todo iterator aligned even for hidden todo blocks
        let todo = if x.kind == "todo" {
            ti.next().cloned()
        } else {
            None
        };
        let hidden = match hide_level {
            Some(l) if level <= l => {
                hide_level = None;
                false
            }
            Some(_) => true,
            None => false,
        };
        if hidden {
            continue;
        }
        let bid = idx as i32;
        if x.kind == "typst" {
            if render_typst {
                if let Some(png) = b.render_typst_src(&x.text) {
                    if let Ok(img) = slint::Image::load_from_path(&png) {
                        let (task_kind, project, person, due, priority) = empty_task_fields();
                        out.push(MdBlock {
                            kind: "typst".into(),
                            text: "".into(),
                            indent: x.indent,
                            img,
                            todo_id: "".into(),
                            done: false,
                            status: "".into(),
                            task_kind,
                            project,
                            person,
                            due,
                            priority,
                            segments: no_segs(),
                            block_id: bid,
                            folded: false,
                        });
                        continue;
                    }
                }
            }
            let (task_kind, project, person, due, priority) = empty_task_fields();
            out.push(MdBlock {
                kind: "code".into(),
                text: x.text.clone().into(),
                indent: x.indent,
                img: empty.clone(),
                todo_id: "".into(),
                done: false,
                status: "".into(),
                task_kind,
                project,
                person,
                due,
                priority,
                segments: no_segs(),
                block_id: bid,
                folded: false,
            });
        } else if x.kind == "todo" {
            let t = todo.as_ref();
            let id = t.map(|t| t.id.clone()).unwrap_or_default();
            let done = t.map(|t| t.done).unwrap_or(false);
            let status = t.map(|t| t.status.clone()).unwrap_or_default();
            let prio = t.map(|t| t.priority.clone()).unwrap_or_default();
            out.push(MdBlock {
                kind: "todo".into(),
                text: t
                    .map(|t| t.text.clone())
                    .unwrap_or_else(|| x.text.clone())
                    .into(),
                indent: x.indent,
                img: empty.clone(),
                todo_id: id.into(),
                done,
                status: status.into(),
                task_kind: t.map(|t| t.kind.clone()).unwrap_or_default().into(),
                project: t.map(|t| t.project.clone()).unwrap_or_default().into(),
                person: t.map(|t| t.person.clone()).unwrap_or_default().into(),
                due: t.map(|t| t.due.clone()).unwrap_or_default().into(),
                priority: prio.into(),
                segments: no_segs(),
                block_id: bid,
                folded: false,
            });
        } else if x.kind == "code" || x.kind == "rule" {
            let (task_kind, project, person, due, priority) = empty_task_fields();
            out.push(MdBlock {
                kind: x.kind.clone().into(),
                text: x.text.clone().into(),
                indent: x.indent,
                img: empty.clone(),
                todo_id: "".into(),
                done: false,
                status: "".into(),
                task_kind,
                project,
                person,
                due,
                priority,
                segments: no_segs(),
                block_id: bid,
                folded: false,
            });
        } else if level <= 3 {
            let is_folded = folded.contains(&idx);
            let (task_kind, project, person, due, priority) = empty_task_fields();
            out.push(MdBlock {
                kind: x.kind.clone().into(),
                text: backend::clean_inline(&x.text).into(),
                indent: x.indent,
                img: empty.clone(),
                todo_id: "".into(),
                done: false,
                status: "".into(),
                task_kind,
                project,
                person,
                due,
                priority,
                segments: no_segs(),
                block_id: bid,
                folded: is_folded,
            });
            if is_folded {
                hide_level = Some(level);
            }
        } else {
            let inline = matches!(x.kind.as_str(), "para" | "bullet" | "numbered" | "quote");
            let segs = if inline {
                backend::line_segments(&x.text)
            } else {
                Vec::new()
            };
            let has_link = segs.iter().any(|s| !s.kind.is_empty());
            if has_link && x.text.chars().count() < 160 {
                let sm: Vec<Segment> = segs
                    .iter()
                    .map(|s| Segment {
                        text: s.text.clone().into(),
                        kind: s.kind.clone().into(),
                        value: s.value.clone().into(),
                    })
                    .collect();
                let (task_kind, project, person, due, priority) = empty_task_fields();
                out.push(MdBlock {
                    kind: x.kind.clone().into(),
                    text: "".into(),
                    indent: x.indent,
                    img: empty.clone(),
                    todo_id: "".into(),
                    done: false,
                    status: "".into(),
                    task_kind,
                    project,
                    person,
                    due,
                    priority,
                    segments: ModelRc::new(VecModel::from(sm)),
                    block_id: bid,
                    folded: false,
                });
            } else {
                let (task_kind, project, person, due, priority) = empty_task_fields();
                out.push(MdBlock {
                    kind: x.kind.clone().into(),
                    text: backend::clean_inline(&x.text).into(),
                    indent: x.indent,
                    img: empty.clone(),
                    todo_id: "".into(),
                    done: false,
                    status: "".into(),
                    task_kind,
                    project,
                    person,
                    due,
                    priority,
                    segments: no_segs(),
                    block_id: bid,
                    folded: false,
                });
            }
        }
    }
    ModelRc::new(VecModel::from(out))
}

fn str_model(v: &[String]) -> ModelRc<SharedString> {
    ModelRc::new(VecModel::from(
        v.iter()
            .map(|s| SharedString::from(s.as_str()))
            .collect::<Vec<_>>(),
    ))
}

fn clip_set(text: &str) {
    if let Ok(mut c) = arboard::Clipboard::new() {
        let _ = c.set_text(text.to_string());
    }
}

