pub(crate) struct PreviewAiRuntime;

impl StructuredRuntime for PreviewAiRuntime {
    fn complete_structured<T>(&self, request: StructuredRequest) -> AiResult<StructuredResponse<T>>
    where
        T: for<'de> serde::Deserialize<'de> + serde::Serialize,
    {
        let value = match request.task {
            StructuredTask::DraftOneOnOneAgenda => serde_json::to_value(AgendaDraft {
                person: person_from_agenda_instructions(&request.instructions),
                sections: vec![AgendaSection {
                    title: "Suggested agenda".into(),
                    items: request
                        .context
                        .iter()
                        .take(5)
                        .map(|block| AgendaItem {
                            text: block
                                .title
                                .clone()
                                .unwrap_or_else(|| "Review source context".into()),
                            sources: vec![block.source.clone()],
                        })
                        .collect(),
                }],
            }),
            StructuredTask::ReviewNote => serde_json::to_value(NoteReview {
                findings: vec![ReviewFinding {
                    kind: ReviewFindingKind::OpenQuestion,
                    text: "Review this note for decisions, risks, commitments, and missing task ownership.".into(),
                    sources: request
                        .context
                        .first()
                        .map(|block| vec![block.source.clone()])
                        .unwrap_or_default(),
                }],
                label_suggestions: vec![LabelSuggestion {
                    label: "review".into(),
                    reason: "Generated by local preview review action.".into(),
                    sources: request
                        .context
                        .first()
                        .map(|block| vec![block.source.clone()])
                        .unwrap_or_default(),
                }],
                task_extractions: request
                    .context
                    .first()
                    .map(|block| {
                        vec![TaskExtraction {
                            text: "Review extracted follow-ups".into(),
                            person: None,
                            due: None,
                            labels: vec!["followup".into()],
                            source: block.source.clone(),
                        }]
                    })
                    .unwrap_or_default(),
            }),
            _ => serde_json::to_value(NoteReview {
                findings: Vec::new(),
                label_suggestions: Vec::new(),
                task_extractions: Vec::new(),
            }),
        }
        .map_err(|err| noet_ai::AiRuntimeError::StructuredOutputFailed {
            message: err.to_string(),
        })?;
        let value = serde_json::from_value(value).map_err(|err| {
            noet_ai::AiRuntimeError::StructuredOutputFailed {
                message: err.to_string(),
            }
        })?;
        Ok(StructuredResponse {
            value,
            usage: Some(AiUsage {
                input_tokens: None,
                output_tokens: None,
            }),
        })
    }
}

pub(crate) struct PreviewEmbeddingRuntime;

impl EmbeddingRuntime for PreviewEmbeddingRuntime {
    fn embed(&self, request: EmbeddingRequest) -> AiResult<EmbeddingResponse> {
        Ok(EmbeddingResponse {
            vectors: request
                .inputs
                .into_iter()
                .map(|input| EmbeddingVector {
                    id: input.id,
                    values: preview_embedding(&input.text),
                })
                .collect(),
            usage: Some(AiUsage {
                input_tokens: None,
                output_tokens: None,
            }),
        })
    }
}

pub(crate) fn local_runtime_settings(settings: &AiSettings) -> LocalRuntimeSettings {
    let model_root = settings.model_root.clone();
    let timeout_seconds = settings.timeout_seconds;
    let mut runtime_settings = LocalRuntimeSettings::embedded();
    runtime_settings.models = local_model_specs(Path::new(&model_root));
    runtime_settings.timeout_seconds = timeout_seconds;
    runtime_settings
}

pub(crate) fn use_preview_ai_runtime() -> bool {
    match std::env::var("NOET_AI_RUNTIME") {
        Ok(value) if value.eq_ignore_ascii_case("local") => false,
        Ok(value) if value.eq_ignore_ascii_case("preview") => true,
        _ => cfg!(test),
    }
}

