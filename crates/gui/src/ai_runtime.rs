pub(crate) fn require_free_memory(min_percent: u8) -> Result<(), String> {
    match current_free_memory_percent() {
        Some(free) if free < min_percent => Err(format!(
            "AI memory preflight failed: {free}% free, requires {min_percent}%"
        )),
        _ => Ok(()),
    }
}

fn preview_embedding(text: &str) -> Vec<f32> {
    let lower = text.to_lowercase();
    let launch = if lower.contains("launch") { 1.0 } else { 0.0 };
    let budget = if lower.contains("budget") { 1.0 } else { 0.0 };
    let followup = if lower.contains("follow") || lower.contains("task") {
        1.0
    } else {
        0.0
    };
    let meeting = if lower.contains("meeting") || lower.contains("agenda") {
        1.0
    } else {
        0.0
    };
    vec![launch, budget, followup, meeting]
}

fn resolve_model_dir(model_root: &Path, owner: &str, repo: &str, file: &str) -> PathBuf {
    let direct = model_root.join(file);
    if direct.exists() {
        return model_root.to_path_buf();
    }
    let repo_dir = model_root.join(owner).join(repo);
    if repo_dir.join(file).exists() {
        return repo_dir;
    }
    let hf_repo = model_root
        .join(format!("models--{owner}--{repo}"))
        .join("snapshots");
    if let Ok(snapshots) = std::fs::read_dir(&hf_repo) {
        for snapshot in snapshots.flatten() {
            let dir = snapshot.path();
            if dir.join(file).exists() {
                return dir;
            }
        }
    }
    model_root.join(format!("models--{owner}--{repo}"))
}

#[cfg(target_os = "macos")]
fn current_free_memory_percent() -> Option<u8> {
    let output = Command::new("memory_pressure").output().ok()?;
    let text = String::from_utf8_lossy(&output.stdout);
    text.lines().find_map(|line| {
        line.split_once("System-wide memory free percentage: ")
            .and_then(|(_, value)| value.trim().trim_end_matches('%').parse::<u8>().ok())
    })
}

#[cfg(not(target_os = "macos"))]
fn current_free_memory_percent() -> Option<u8> {
    None
}

fn person_from_agenda_instructions(instructions: &str) -> String {
    instructions
        .strip_prefix("Draft a concise, source-linked 1:1 agenda for ")
        .and_then(|rest| rest.split('.').next())
        .map(str::trim)
        .filter(|person| !person.is_empty())
        .unwrap_or("Selected person")
        .to_string()
}
